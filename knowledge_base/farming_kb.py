def search_knowledge_base(query: str, category: str = None, top_k: int = 3) -> list:
    """Simple keyword-based RAG search over the knowledge base."""
    query_words = set(query.lower().split())
    scored = []
    for doc in AGRICULTURAL_KNOWLEDGE:
        if category and doc["category"] != category:
            continue
        text = (doc["title"] + " " + doc["content"]).lower()
        score = sum(1 for w in query_words if w in text)
        # Boost for title matches
        title_words = set(doc["title"].lower().split())
        score += sum(2 for w in query_words if w in title_words)
        if score > 0:
            scored.append((score, doc))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [doc for _, doc in scored[:top_k]]

def get_category_docs(category: str) -> list:
    return [doc for doc in AGRICULTURAL_KNOWLEDGE if doc["category"] == category]
